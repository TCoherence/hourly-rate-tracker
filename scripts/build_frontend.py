#!/usr/bin/env python3
"""Build the backwards-compatible browser bootstrap served by old services.

The running service reads this existing static route from disk on each request.
Keep the component files as the source of truth and regenerate after changes.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ("i18n.js", "dashboard-translations.js", "draft-undo.js", "history-calendar-core.js")
TARGET = ROOT / "static" / "history-calendar.js"


def expected_bundle():
    header = "/* Generated by scripts/build_frontend.py. Edit the component files instead. */\n"
    parts = [(ROOT / "static" / name).read_text(encoding="utf-8").rstrip() for name in SOURCES]
    return header + "\n;\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Build or check the browser compatibility bundle")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = expected_bundle()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != expected:
            parser.exit(1, "Browser bundle is stale; run python3 scripts/build_frontend.py\n")
        print("Browser bundle is current")
    else:
        TARGET.write_text(expected, encoding="utf-8")
        print("Built browser compatibility bundle")


if __name__ == "__main__":
    main()
