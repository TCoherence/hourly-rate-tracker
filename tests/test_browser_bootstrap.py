"""The UI remains loadable by older local services with a fixed asset list."""
from html.parser import HTMLParser
import http.client
from pathlib import Path
import shutil
import tempfile
import threading
import unittest
from unittest.mock import patch

from app import Application, LocalServer, handler_for
import build_preview
from scripts.build_frontend import ROOT, TARGET, expected_bundle


class ScriptSources(HTMLParser):
    def __init__(self):
        super().__init__()
        self.sources = []

    def handle_starttag(self, tag, attrs):
        if tag == "script":
            source = dict(attrs).get("src")
            if source:
                self.sources.append(source)


class BrowserBootstrapTests(unittest.TestCase):
    def test_bundle_is_current_and_pages_use_existing_routes(self):
        self.assertEqual(TARGET.read_text(encoding="utf-8"), expected_bundle())
        allowed = {"/theme.js", "/history-calendar.js", "/app.js", "/manual.js", "/logs.js"}
        for name in ("index.html", "logs.html"):
            page = ScriptSources()
            page.feed((ROOT / "static" / name).read_text(encoding="utf-8"))
            self.assertFalse(set(page.sources) - allowed, name)
            self.assertIn("/history-calendar.js", page.sources)
            self.assertLess(page.sources.index("/history-calendar.js"),
                            page.sources.index("/app.js" if name == "index.html" else "/logs.js"))

    def test_new_service_serves_bootstrap_with_same_origin_script_policy(self):
        with tempfile.TemporaryDirectory() as directory:
            app = Application(directory, detector=lambda _: ("disabled", "test"))
            server = LocalServer(("127.0.0.1", 0), handler_for(app))
            thread = threading.Thread(target=server.serve_forever, kwargs={"poll_interval": 0.01}, daemon=True)
            thread.start()
            connection = http.client.HTTPConnection("127.0.0.1", server.server_address[1], timeout=3)
            try:
                connection.request("GET", "/history-calendar.js")
                response = connection.getresponse()
                body = response.read().decode("utf-8")
                self.assertEqual(response.status, 200)
                self.assertIn("text/javascript", response.getheader("Content-Type"))
                self.assertIn("script-src 'self'", response.getheader("Content-Security-Policy"))
                self.assertEqual(body, expected_bundle())
            finally:
                connection.close()
                server.shutdown()
                server.server_close()
                thread.join(timeout=2)
                app.close()

    def test_offline_preview_contains_inlined_bootstrap(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            shutil.copytree(ROOT / "static", root / "static")
            with patch.object(build_preview, "ROOT", root):
                build_preview.build()
            html = (root / "preview.html").read_text(encoding="utf-8")
            self.assertNotIn('src="/history-calendar.js"', html)
            self.assertIn("Generated by scripts/build_frontend.py", html)
            self.assertIn("hourly-rate-language", html)


if __name__ == "__main__":
    unittest.main()
